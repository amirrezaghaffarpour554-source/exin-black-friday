/* Real browser checks against scripts/test-runtime.sh's local WordPress only. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright');
const project = path.resolve(__dirname, '../..');
const output = path.join(project, 'work/browser');
fs.mkdirSync(output, {recursive: true});
const fixture = JSON.parse(execFileSync('bash', [path.join(project, 'scripts/test-runtime.sh'), 'wp', 'eval-file', '/var/www/html/wp-content/plugins/exin-black-friday/tests/integration/browser-fixture.php'], {cwd: project, encoding: 'utf8'}));
(async () => {
    const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    let checks = 0;
    const check = (condition, message) => { assert.ok(condition, message); checks++; };
    try {
        await page.goto('http://localhost:8880/wp-login.php');
        await page.locator('#user_login').fill('exin_test');
        await page.locator('#user_pass').fill('exin-local-only');
        await Promise.all([page.waitForURL(/wp-admin/), page.locator('#wp-submit').click()]);
        await page.goto('http://localhost:8880/wp-admin/admin.php?page=exin-black-friday');
        await page.getByRole('heading', {name: 'EXIN Browser Workflow'}).waitFor();
        check(await page.locator('#exin-bf-message').isHidden(), 'Plain permalink REST loads dashboard');
        await page.locator('[data-view="settings"]').click();
        await page.locator('#exin-bf-settings').waitFor();
        check(await page.locator('#bf-timezone').inputValue() === 'Asia/Tehran', 'Default timezone is Tehran');
        const startLocal = new Intl.DateTimeFormat('sv-SE', {timeZone: 'Asia/Tehran', year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false}).format(new Date(Date.now() - 3600000)).replace(' ', 'T');
        await page.locator('#bf-start_local').fill(startLocal);
        await page.locator('#exin-bf-settings button[type="submit"]').click();
        await page.locator('.exin-bf-table').waitFor();
        check((await page.locator('#exin-bf-content').innerText()).includes('محصولی اضافه نشده'), 'Draft settings save through actual REST');
        const started = performance.now();
        await page.locator('header [data-command="add"]').click();
        await page.locator('#exin-bf-product-search').fill(fixture.sku);
        await page.locator(`[data-choose-product="${fixture.product_id}"]`).click();
        await page.locator('#bf-floor_price').fill('60.00');
        await page.locator('[data-command="preview"]').click();
        await page.locator('#exin-bf-preview > span').nth(6).waitFor();
        check(await page.locator('#exin-bf-preview > span').count() === 7, 'Preview has exactly seven days');
        check((await page.locator('#exin-bf-preview > span').nth(0).innerText()).includes('100.00'), 'Preview starts at valid base');
        check((await page.locator('#exin-bf-preview > span').nth(6).innerText()).includes('60.00'), 'Preview ends at floor');
        await page.locator('#exin-bf-add-form button[type="submit"]').click();
        const row = page.locator(`[data-product-row="${fixture.product_id}"]`);
        await row.waitFor();
        const enrollmentSeconds = (performance.now() - started) / 1000;
        check(enrollmentSeconds < 60, 'Enrollment completes within sixty seconds');
        check((await row.innerText()).includes('60.00'), 'Saved floor visible in admin');
        await row.locator('[data-command="item-edit"]').click();
        await page.locator('#bf-floor_price').fill('50.00');
        await page.locator('#exin-bf-edit-form [name="featured"]').check();
        await page.locator('#exin-bf-edit-form button[type="submit"]').click();
        await page.waitForFunction(id => document.querySelector(`[data-product-row="${id}"]`)?.textContent.includes('50.00'), fixture.product_id);
        check(await row.locator('[data-featured]').isChecked(), 'Floor edit and featured flag persist');
        await page.screenshot({path: path.join(output, 'admin-desktop.png'), fullPage: true});
        await page.locator('[data-view="dashboard"]').click();
        await page.locator('[data-command="start"]').waitFor();
        check(await page.locator('[data-command="start"]').isVisible(), 'Draft whose start has passed offers immediate start');
        await page.locator('[data-command="start"]').click();
        await page.locator('.exin-bf-hero [data-status="active"]').waitFor();
        check(await page.locator('[data-command="pause"]').isVisible(), 'Actual dashboard starts campaign');
        page.once('dialog', dialog => dialog.accept());
        await page.locator('[data-command="pause"]').click();
        await page.locator('.exin-bf-hero [data-status="paused"]').waitFor();
        check(await page.locator('[data-command="resume"]').isVisible(), 'Pause is distinct from restoration');
        await page.locator('[data-command="resume"]').click();
        await page.locator('.exin-bf-hero [data-status="active"]').waitFor();
        check(await page.locator('[data-command="restore"]').isVisible(), 'Resume retains separate explicit restoration action');
        await page.locator('[data-view="diagnostics"]').click();
        await page.locator('.exin-bf-health').waitFor();
        check((await page.locator('.exin-bf-health').innerText()).includes('10.3.0'), 'Diagnostics read actual Woo version');
        await page.setViewportSize({width: 390, height: 844});
        await page.locator('[data-view="products"]').click();
        await page.locator('.exin-bf-table').waitFor();
        check(await page.locator('body').evaluate(element => element.scrollWidth) <= 390, 'Mobile page has no horizontal overflow');
        await row.locator('[data-command="item-edit"]').click();
        await page.locator('dialog[open]').waitFor();
        check(await page.locator('dialog[open]').evaluate(element => element.getBoundingClientRect().width) <= 390, 'Mobile dialog fits viewport');
        check(await page.locator('#bf-floor_price').isDisabled(), 'Active campaign locks financial floor editing');
        await page.locator('[data-command="close-dialog"]').click();
        await page.screenshot({path: path.join(output, 'admin-mobile.png'), fullPage: true});
        check(errors.length === 0, 'No browser JavaScript exceptions');
        const report = {checks, failed: 0, enrollment_seconds: Number(enrollmentSeconds.toFixed(3)), viewport: [1440, 1000, 390, 844], errors};
        fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report, null, 2) + '\n');
        console.log(JSON.stringify(report));
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
