/* Real HTTP WordPress/WooCommerce admin workflow. No REST routing or mocks. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');
const {chromium} = require('playwright');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'work/v101/admin-wordpress');
const base = new URL(process.env.EXIN_WP_BASE_URL || 'http://127.0.0.1:8891');
if (!['localhost', '127.0.0.1', '[::1]'].includes(base.hostname)) throw new Error('Real admin browser checks require a loopback URL.');
if (process.env.EXIN_V101_RUNTIME_LEASE !== 'admin') throw new Error('Obtain the isolated runtime lease and set EXIN_V101_RUNTIME_LEASE=admin first.');
fs.mkdirSync(output, {recursive: true});
const fixturePath = process.env.EXIN_WP_FIXTURE_PATH || path.join(root, 'tests/browser/v101-admin-fixture.php');
const driver = process.env.EXIN_WP_TEST_DRIVER || path.join(root, 'scripts/test-v101-native.sh');
const fixtureRun = mode => JSON.parse(execFileSync('bash', [driver, 'wp', 'eval-file', fixturePath, mode], {cwd: root, encoding: 'utf8', maxBuffer: 1024 * 1024}));
const fixture = fixtureRun('prepare'); // Generated test password stays in memory, never in reports.
const errors = [], calls = [];
let checks = 0;
const check = (condition, label) => { assert.ok(condition, label); checks++; console.log('PASS ' + label); };
const endpoint = url => {
    const parsed = new URL(url);
    return parsed.searchParams.get('rest_route') || parsed.pathname.replace(/^\/wp-json/, '');
};
(async () => {
    const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    page.setDefaultTimeout(30000);
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {
        if (!endpoint(request.url()).startsWith('/exin-bf/v1/admin/')) return;
        calls.push({endpoint: endpoint(request.url()).replace('/exin-bf/v1/admin/', ''), method: request.method(), body: request.method() === 'POST' ? request.postDataJSON() : null});
    });
    const api = async (route, payload, nonceMode = 'valid') => page.evaluate(async ({route, payload, nonceMode}) => {
        const config = window.exinBFAdmin, url = new URL(config.root), relative = new URL(route, 'http://local.invalid/');
        if (url.searchParams.has('rest_route')) url.searchParams.set('rest_route', url.searchParams.get('rest_route') + relative.pathname.slice(1));
        else url.pathname += relative.pathname.slice(1);
        relative.searchParams.forEach((value, key) => url.searchParams.set(key, value));
        const headers = {'Content-Type': 'application/json'};
        if (nonceMode !== 'missing') headers['X-WP-Nonce'] = nonceMode === 'valid' ? config.nonce : 'invalid-local-test-nonce';
        const response = await fetch(url, {method: payload === undefined ? 'GET' : 'POST', credentials: 'same-origin', headers, body: payload === undefined ? undefined : JSON.stringify(payload)});
        return {status: response.status, value: await response.json()};
    }, {route, payload, nonceMode});
    const waitSaved = () => page.waitForFunction(() => document.getElementById('exin-bf-draft-status')?.dataset.state === 'saved');
    const waitRest = suffix => page.waitForResponse(response => endpoint(response.url()).endsWith(suffix) && response.request().method() === 'POST');
    const campaignRoute = suffix => `campaign/${fixture.campaign_id}/${suffix}`;
    let setupSeconds = null, enrollmentSeconds = null;
    try {
        await page.goto(new URL('/wp-login.php', base).href);
        await page.locator('#user_login').fill(fixture.username);
        await page.locator('#user_pass').fill(fixture.password);
        await Promise.all([page.waitForURL(/wp-admin/), page.locator('#wp-submit').click()]);
        await page.goto(new URL('/wp-admin/admin.php?page=exin-black-friday', base).href);
        await page.locator('.exin-bf-hero').waitFor();
        check(await page.locator('#exin-bf-message').isHidden(), 'Actual authenticated WordPress REST loads the campaign dashboard');
        const anonymous = await browser.newContext();
        const stateUrl = await page.evaluate(() => {
            const url = new URL(window.exinBFAdmin.root);
            if (url.searchParams.has('rest_route')) url.searchParams.set('rest_route', url.searchParams.get('rest_route') + 'state');
            else url.pathname += 'state';
            return url.href;
        });
        check((await anonymous.request.get(stateUrl)).status() === 403, 'Actual REST rejects anonymous access to campaign data');
        await anonymous.close();
        check((await api('state', undefined, 'missing')).status === 403 && (await api('state', undefined, 'invalid')).status === 403, 'Actual REST rejects missing and invalid nonces');
        const health = (await api('state?view=diagnostics')).value.health;
        check(health.wordpress === '7.1.4' && health.woocommerce === '11.3.0' && health.php.startsWith('8.2.'), 'Browser receives actual requested WordPress WooCommerce PHP matrix');
        await page.locator('[data-view="settings"]').click();
        await page.locator('#exin-bf-settings').waitFor();
        const setupStarted = performance.now();
        check(await page.locator('[data-step]').count() === 3, 'Actual setup shows three steps');
        check(await page.locator('#bf-start_jalali').inputValue() === fixture.date_jalali, 'Actual stored date displays as Jalali Persian digits');
        check(await page.locator('#bf-start_time').getAttribute('type') === 'text', 'Actual clock has explicit24-hour text');
        check(!(await page.locator('#exin-bf-admin').innerText()).includes('هدف سفارش'), 'Actual admin has no order-goal setting');
        await page.locator('.exin-bf-calendar-toggle').click();
        check(await page.locator('.exin-bf-calendar').isVisible(), 'Actual Jalali calendar opens');
        await page.screenshot({path: path.join(output, 'desktop-jalali.png'), fullPage: true});
        await page.keyboard.press('Escape');
        await page.locator('#bf-title').fill(fixture.prefix + ' saved draft');
        await page.locator('#bf-start_time').fill('۲۳:۵۹');
        await page.locator('[data-view="products"]').click();
        await page.locator('.exin-bf-table').waitFor();
        check(calls.filter(call => call.endpoint === 'campaign').at(-1).body.start_time === '23:59', 'Actual autosave normalizes Persian24-hour input');
        check(calls.every(call => !call.endpoint.endsWith('/action')), 'Actual draft autosave sends no activation action');
        await page.locator('[data-view="settings"]').click();
        await page.locator('#exin-bf-settings').waitFor();
        check(await page.locator('#bf-title').inputValue() === fixture.prefix + ' saved draft', 'Actual draft survives tab navigation');
        await page.locator('#bf-title').fill(fixture.prefix + ' autosaved draft');
        await waitSaved();
        check((await api('state')).value.campaign.title.endsWith('autosaved draft'), 'Actual debounce saves without submitting the form');
        setupSeconds = Number(((performance.now() - setupStarted) / 1000).toFixed(3));
        check(setupSeconds < 60, 'Actual primary setup and saved tab navigation complete within60seconds');
        await page.locator('#bf-start_time').fill('۲۵:۹۹');
        await page.locator('[data-view="products"]').click();
        await page.locator('.exin-bf-table').waitFor();
        check(await page.locator('#exin-bf-draft-status').getAttribute('data-state') === 'error', 'Invalid clock input shows a visible draft error');
        await page.locator('[data-view="settings"]').click();
        await page.locator('#exin-bf-settings').waitFor();
        check(await page.locator('#bf-start_time').inputValue() === '۲۵:۹۹', 'Invalid unsaved input survives navigation for correction');
        await page.locator('#bf-start_time').fill('۲۳:۵۹');
        await waitSaved();
        const enrollmentStarted = performance.now();
        await page.locator('header [data-command="add"]').click();
        await page.locator('[data-picker-filter="category"] option[value="' + fixture.category_id + '"]').waitFor({state: 'attached'});
        await page.locator('[data-picker-filter="category"]').selectOption(String(fixture.category_id));
        await page.locator('[data-picker-filter="type"]').selectOption('simple');
        await page.locator('[data-picker-taxonomy="product_brand"]').selectOption(fixture.brand_slug);
        await page.locator(`[data-picker-taxonomy="${fixture.attribute_taxonomy}"]`).selectOption(fixture.attribute_slug);
        await page.locator(`[data-picker-select="${fixture.simple_ids[0]}"]`).waitFor();
        await page.locator('[data-command="picker-select-filtered"]').click();
        await page.waitForFunction(() => document.querySelectorAll('[data-picker-floor]').length === 28);
        check(await page.locator('[data-picker-floor]').count() === 28, 'Actual category brand attribute filters select28 matching simple products across pages');
        await page.locator('#bf-common_floor').fill('۴۰٬۰۰۰');
        await page.locator('[data-command="picker-apply-floor"]').click();
        await page.locator(`[data-picker-floor="${fixture.simple_ids[1]}"]`).fill('60,000');
        await page.locator(`[data-command="picker-preview"][data-id="${fixture.simple_ids[1]}"]`).click();
        await page.locator(`#exin-bf-preview-${fixture.simple_ids[1]} > span`).nth(6).waitFor();
        check((await page.locator(`#exin-bf-preview-${fixture.simple_ids[1]} > span`).nth(6).innerText()).includes('60,000'), 'Actual seven-day preview ends at independently entered Toman floor');
        await page.locator('[data-command="picker-save"]').click();
        await page.locator('dialog[open]').waitFor({state: 'hidden'});
        await page.locator('.exin-bf-table').waitFor();
        const enrolled = (await api('state?view=products')).value;
        check(enrolled.count === 28 && enrolled.items.find(item => item.product_id === fixture.simple_ids[1]).floor_price === '600000', 'Actual REST stores independent Toman floors exactly once as canonical IRR');
        const batches = calls.filter(call => call.endpoint.endsWith('/bulk'));
        check(batches.length === 2 && batches.every(call => call.body.items.length <= 25), 'Actual28-product save uses25+3 bounded writes');
        enrollmentSeconds = Number(((performance.now() - enrollmentStarted) / 1000).toFixed(3));
        check(enrollmentSeconds < 60, 'Actual filtered28-product enrollment completes within60seconds');
        await page.locator('header [data-command="add"]').click();
        await page.locator('#exin-bf-product-search').fill(fixture.prefix);
        await page.locator(`[data-picker-select="${fixture.simple_ids[0]}"]`).waitFor();
        check(await page.locator(`[data-picker-select="${fixture.simple_ids[0]}"]`).isDisabled(), 'Actual campaign membership prevents duplicate selection in later sessions');
        await page.locator('[data-picker-filter="type"]').selectOption('variable');
        await page.locator(`[data-picker-parent="${fixture.parent_id}"]`).waitFor();
        check(await page.locator(`[data-picker-select="${fixture.parent_id}"]`).isDisabled(), 'Actual variable parent is navigation only');
        await page.locator(`[data-picker-parent="${fixture.parent_id}"]`).click();
        await page.locator(`[data-picker-select="${fixture.variation_ids[0]}"]`).check();
        await page.locator(`[data-picker-floor="${fixture.variation_ids[0]}"]`).fill('۵۰٬۰۰۰');
        await page.locator('[data-command="picker-save"]').click();
        await page.locator('dialog[open]').waitFor({state: 'hidden'});
        check((await api('state?view=products')).value.count === 29, 'Actual sellable variation enrolls independently');
        check(fixtureRun('verify').unchanged_prices_and_stock, 'Actual draft setup enrollment and preview preserve every Woo price and stock field');
        await page.locator(`[data-featured="${fixture.simple_ids[0]}"]`).check();
        await page.locator(`[data-product-row="${fixture.simple_ids[0]}"][draggable="true"]`).waitFor();
        await page.locator(`[data-featured="${fixture.simple_ids[1]}"]`).check();
        await page.locator(`[data-product-row="${fixture.simple_ids[1]}"][draggable="true"]`).waitFor();
        await Promise.all([
            waitRest('/reorder'),
            page.locator(`[data-product-row="${fixture.simple_ids[1]}"] .exin-bf-product`).dragTo(page.locator(`[data-product-row="${fixture.simple_ids[0]}"] .exin-bf-product`), {targetPosition: {x: 20, y: 5}})
        ]);
        await page.waitForFunction(id => document.querySelector('[data-product-row]')?.dataset.productRow === String(id), fixture.simple_ids[1]);
        check((await api('state?view=products')).value.items[0].product_id === fixture.simple_ids[1], 'Actual featured drag-and-drop persists the manual order through REST');
        await page.setViewportSize({width: 390, height: 844});
        await page.locator('header [data-command="add"]').click();
        await page.locator('#exin-bf-product-search').fill(fixture.prefix);
        await page.locator(`[data-picker-select="${fixture.simple_ids[0]}"]`).waitFor();
        check(await page.locator('dialog[open]').evaluate(node => node.getBoundingClientRect().width <= 390), 'Actual mobile product picker fits390px');
        await page.screenshot({path: path.join(output, 'mobile-picker.png'), fullPage: true});
        await page.locator('[data-command="close-dialog"]').first().click();
        await page.setViewportSize({width: 1440, height: 1000});
        await page.locator('[data-view="diagnostics"]').click();
        await page.locator('#exin-bf-report-settings').waitFor();
        check(await page.locator('[name="order_status"][value="exin-ui-paid"]').count() === 1 && await page.locator('[name="order_status"][value="refunded"]').count() === 0, 'Actual registered custom status appears and refunded is excluded');
        await page.locator('[name="order_status"][value="exin-ui-paid"]').check();
        await Promise.all([waitRest('/report-settings'), page.locator('#exin-bf-report-settings button[type="submit"]').click()]);
        await page.locator('[data-view="settings"]').click();
        await page.locator('#bf-title').fill(fixture.prefix + ' report policy preserved');
        await waitSaved();
        check((await api('state')).value.campaign.settings.order_statuses.includes('exin-ui-paid'), 'Actual subsequent draft autosave preserves custom report statuses');
        const rejected = await api(campaignRoute('action'), {action: 'schedule'});
        check(rejected.status === 400 && (await api('state')).value.campaign.status === 'draft', 'Actual server rejects activation without explicit confirmation');
        await page.locator('[data-step="3"]').click();
        await page.locator('#exin-bf-confirm-activate').waitFor();
        check(await page.locator('#exin-bf-activate').isDisabled(), 'Actual review requires an explicit manager checkbox');
        await page.locator('#exin-bf-confirm-activate').check();
        await page.locator('#exin-bf-activate').click();
        await page.locator('.exin-bf-hero [data-status="scheduled"]').waitFor();
        check(calls.filter(call => call.endpoint.endsWith('/action') && call.body.confirm_activate === true).length === 1, 'Actual UI emits exactly one explicitly confirmed activation');
        page.once('dialog', dialog => dialog.accept());
        await page.locator('[data-command="pause"]').click();
        await page.locator('.exin-bf-hero [data-status="paused"]').waitFor();
        page.once('dialog', dialog => dialog.accept());
        await page.locator('[data-command="resume"]').click();
        await page.locator('.exin-bf-hero [data-status="scheduled"]').waitFor();
        check((await api('state')).value.campaign.status === 'scheduled', 'Actual pause and resume retain future scheduled lifecycle');
        await page.setViewportSize({width: 390, height: 844});
        await page.locator('[data-view="products"]').click();
        await page.locator(`[data-command="item-edit"][data-id="${fixture.simple_ids[0]}"]`).click();
        await page.locator('dialog[open]').waitFor();
        check(await page.locator('#bf-floor_price').isDisabled(), 'Actual scheduled campaign locks financial floor editing');
        check(await page.locator('dialog[open]').evaluate(node => node.getBoundingClientRect().width <= 390), 'Actual WordPress mobile dialog fits390px');
        await page.screenshot({path: path.join(output, 'mobile-edit.png'), fullPage: true});
        await page.locator('[data-command="close-dialog"]').first().click();
        check(await page.locator('body').evaluate(node => node.scrollWidth <= 390), 'Actual WordPress admin has no mobile page-level horizontal overflow');
        check(fixtureRun('verify').unchanged_prices_and_stock, 'Actual future activation pause and resume preserve Woo prices and stock');
        check(errors.length === 0, 'Actual HTTP browser workflow has no JavaScript exceptions');
        const report = {suite: 'v101-admin-browser-real-wordpress', boundary: 'Real loopback HTTP WordPress/WooCommerce, authenticated cookies and nonce, no REST mocks; synthetic local exin_test data only.', checks, passed: checks, failed: 0, wordpress: health.wordpress, woocommerce: health.woocommerce, php: health.php, setup_seconds: setupSeconds, enrollment_seconds: enrollmentSeconds, viewport: [[1440, 1000], [390, 844]], errors};
        fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report, null, 2) + '\n');
        console.log('EXIN_ADMIN_WORDPRESS_BROWSER_RESULT ' + JSON.stringify(report));
    } catch (error) {
        await page.screenshot({path: path.join(output, 'failure.png'), fullPage: true}).catch(() => {});
        fs.writeFileSync(path.join(output, 'failure.json'), JSON.stringify({error: error.message, url: page.url(), errors, message: await page.locator('#exin-bf-message').innerText().catch(() => ''), content: await page.locator('#exin-bf-content').innerText().catch(() => '')}, null, 2) + '\n');
        throw error;
    } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
