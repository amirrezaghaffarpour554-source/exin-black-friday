/* Isolated real Chromium interaction tests: calendar, exact amounts and cursor. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');
const project = path.resolve(__dirname, '../..');
const output = path.join(project, 'work/v101');
fs.mkdirSync(output, {recursive: true});
(async () => {
    const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']});
    const page = await browser.newPage({viewport: {width: 390, height: 844}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('**/*', route => route.abort());
    let checks = 0;
    const check = (condition, message) => { assert.ok(condition, message); checks++; };
    try {
        await page.setContent('<!doctype html><html lang="fa" dir="rtl"><head><meta name="viewport" content="width=device-width,initial-scale=1"></head><body style="font-family:Tahoma;margin:16px"><form><div style="position:relative;display:flex;flex-direction:column;gap:8px"><label for="date">تاریخ شروع</label><input id="date" data-exin-jalali data-timezone="Asia/Tehran" value="۱۴۰۵/۰۹/۰۶"></div><div style="margin-top:24px"><label for="amount">مبلغ</label><input id="amount" data-exin-money value=""></div></form></body></html>');
        await page.addStyleTag({path: path.join(project, 'assets/admin-helpers.css')});
        await page.addScriptTag({path: path.join(project, 'assets/admin-helpers.js')});
        await page.evaluate(() => { ExinBFHelpers.attach(document); ExinBFHelpers.attach(document); });
        check(await page.locator('.exin-bf-calendar-toggle').count() === 1, 'Repeated attachment does not duplicate calendar controls');
        await page.locator('#amount').fill('۱۲۳۴۵۶۷');
        check(await page.locator('#amount').inputValue() === '1,234,567', 'Persian digits format during typing');
        check(await page.locator('#amount').evaluate(input => input.selectionStart) === 9, 'Caret stays at the end of typed digits');
        await page.locator('#amount').evaluate(input => input.setSelectionRange(2, 2));
        await page.keyboard.insertText('9');
        check(await page.locator('#amount').inputValue() === '19,234,567', 'Middle insertion preserves the exact value');
        check(await page.locator('#amount').evaluate(input => input.selectionStart) === 2, 'Middle insertion caret does not jump to the end');
        await page.locator('#amount').fill('١٢٣٤٫٥٠');
        check(await page.locator('#amount').inputValue() === '1,234.50', 'Arabic digits and decimal separator format consistently');
        await page.locator('#amount').fill('9007199254740993');
        check(await page.locator('#amount').inputValue() === '9,007,199,254,740,993', 'Formatting preserves amounts beyond Number safe integers');
        check(await page.evaluate(() => ExinBFHelpers.toStore('900719925474099.3', 'toman', 'IRR', 0)) === '9007199254740993', 'Browser uses exact BigInt currency conversion');
        await page.locator('.exin-bf-calendar-toggle').click();
        await page.locator('.exin-bf-calendar:not([hidden])').waitFor();
        check((await page.locator('.exin-bf-calendar-header strong').innerText()).includes('آذر ۱۴۰۵'), 'Real calendar opens on the selected Jalali month');
        check(await page.locator('.exin-bf-calendar-grid [data-jalali-date]').count() === 30, 'Azar calendar contains thirty actual day buttons');
        const dimensions = await page.locator('.exin-bf-calendar').evaluate(panel => ({left: panel.getBoundingClientRect().left, right: panel.getBoundingClientRect().right}));
        check(dimensions.left >= 0 && dimensions.right <= 390, 'Calendar fits the mobile viewport');
        await page.locator('[data-jalali-date="1405/09/15"]').click();
        check(await page.locator('#date').inputValue() === '۱۴۰۵/۰۹/۱۵', 'Selecting a day writes the Persian Jalali date');
        check(await page.locator('.exin-bf-calendar').isHidden(), 'Day selection closes the calendar');
        await page.locator('#date').fill('۱۴۰۳/۱۲/۰۱');
        await page.locator('.exin-bf-calendar-toggle').click();
        check(await page.locator('.exin-bf-calendar-grid [data-jalali-date]').count() === 30, 'Leap Esfand includes day thirty');
        await page.locator('[data-jalali-date="1403/12/30"]').click();
        check(await page.evaluate(() => ExinBFHelpers.toGregorian(document.getElementById('date').value)) === '2025-03-20', 'Leap-day selection converts correctly');
        await page.locator('#date').fill('۱۴۰۴/۱۲/۲۹');
        await page.locator('.exin-bf-calendar-toggle').click();
        check(await page.locator('.exin-bf-calendar-grid [data-jalali-date]').count() === 29, 'Nonleap Esfand has only twenty-nine days');
        await page.locator('[data-jalali-date="1404/12/29"]').focus();
        await page.keyboard.press('ArrowLeft');
        check(await page.evaluate(() => document.activeElement.dataset.jalaliDate) === '1405/01/01', 'Keyboard navigation crosses the Jalali year boundary');
        await page.keyboard.press('Enter');
        check(await page.locator('#date').inputValue() === '۱۴۰۵/۰۱/۰۱', 'Keyboard selection writes the new-year day');
        await page.locator('#date').fill('۱۲۰۰/۰۱/۰۱');
        await page.locator('.exin-bf-calendar-toggle').click();
        check(await page.getByRole('button', {name: 'ماه قبل'}).isDisabled(), 'Calendar cannot navigate below the supported range');
        await page.keyboard.press('Escape');
        check(await page.locator('.exin-bf-calendar').isHidden(), 'Escape closes the calendar');
        await page.locator('#date').fill('۱۶۰۰/۱۲/۰۱');
        await page.locator('.exin-bf-calendar-toggle').click();
        check(await page.getByRole('button', {name: 'ماه بعد'}).isDisabled(), 'Calendar cannot navigate above the supported range');
        await page.mouse.click(5, 5);
        check(await page.locator('.exin-bf-calendar').isHidden(), 'Outside click closes the calendar');
        check(errors.length === 0, 'No JavaScript exceptions during helper interactions');
        const report = {suite: 'v101-helper-browser', checks, passed: checks, failed: 0, viewport: [390, 844], errors};
        fs.writeFileSync(path.join(output, 'helper-browser.json'), JSON.stringify(report, null, 2) + '\n');
        console.log('EXIN_HELPER_BROWSER_RESULT ' + JSON.stringify(report));
    } finally {
        await browser.close();
    }
})().catch(error => { console.error(error); process.exitCode = 1; });
